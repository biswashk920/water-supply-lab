"""Bundle data/*.json into docs/presets.js so the static page can load them
without a server (fetch() does not work from file://). Run after editing data/."""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
nets = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(ROOT, "data", "*.json")))]
with open(os.path.join(ROOT, "docs", "presets.js"), "w") as fh:
    fh.write("/* Generated by tools/build_presets.py from data/*.json. Do not edit by hand. */\n")
    fh.write("window.PRESETS = " + json.dumps(nets, indent=1) + ";\n")
print("wrote docs/presets.js with", len(nets), "networks")
